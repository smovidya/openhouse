			ระยะเวลาในการประมวลผลข้อมูลส่วนบุคคลจะอยู่ที่ 270 วัน นับแต่วันที่ดำเนินการเก็บรวบรวมข้อมูลเข้าสู่ระบบ
			เมื่อพ้นระยะเวลาการจัดเก็บ
			ทางโครงการฯ จะไม่มีสิทธิหรือไม่สามารถอ้างฐานในการประมวลข้อมูลส่วนบุคคลของท่านได้อีกต่อไป
			และจะดำเนินการทำลายข้อมูลส่วนบุคคลนั้นด้วยการลบข้อมูลส่วนบุคคลทั้งหมดจนข้อมูลนั้นไม่สามารถระบุได้ถึงตัวเจ้าของข้อมูลส่วนบุคคล
			และจะดำเนินการให้แล้วเสร็จภายใน 90 วันนับแต่วันสิ้นสุดระยะเวลาดังกล่าว
		</p>
	</section>

	<section class="flex flex-col gap-2">
		<h3>7. สิทธิของเจ้าของข้อมูล</h3>
		<ul>
			<li>
				สิทธิในการเพิกถอนความยินยอม (Right to withdraw consent):
				ท่านมีสิทธิในการเพิกถอนความยินยอมในการประมวลผลข้อมูลส่วนบุคคลที่ท่านได้ให้ความยินยอมกับโครงการฯ
				ได้ ตลอดระยะเวลาที่ข้อมูลส่วนบุคคลของท่านอยู่กับโครงการฯ
			</li>
			<li>
				สิทธิในการเข้าถึงข้อมูลส่วนบุคคล (Right to access):
				ท่านมีสิทธิในการเข้าถึงข้อมูลส่วนบุคคลของท่านและขอให้โครงการฯ
				ทำสำเนาข้อมูลส่วนบุคคลดังกล่าวให้แก่ท่าน รวมถึงขอให้โครงการฯ
				เปิดเผยการได้มาซึ่งข้อมูลส่วนบุคคลที่ท่านไม่ได้ให้ความยินยอมต่อโครงการฯ ได้
			</li>
			<li>
				สิทธิในการแก้ไขข้อมูลส่วนบุคคลให้ถูกต้อง (Right of rectification): ท่านมีสิทธิในการขอให้โครงการฯ
				แก้ไขข้อมูลที่ไม่ถูกต้อง หรือเพิ่มเติมข้อมูลที่ไม่สมบูรณ์ได้
			</li>
			<li>
				สิทธิในการลบข้อมูลส่วนบุคคล (Right to erasure): ท่านมีสิทธิในการขอให้โครงการฯ
				ทำการลบข้อมูลของท่านด้วยเหตุบางประการได้
			</li>
			<li>
				สิทธิในการระงับการใช้ข้อมูลส่วนบุคคล (Right to restriction of processing):
				ท่านมีสิทธิในการระงับการใช้ข้อมูลส่วนบุคคลของท่านด้วยเหตุบางประการได้
			</li>
			<li>
				สิทธิในการให้โอนย้ายข้อมูลส่วนบุคคล (Right to data portability):
				ท่านมีสิทธิในการโอนย้ายข้อมูลส่วนบุคคลของท่านที่ท่านให้ไว้กับโครงการฯ ไปยังผู้ควบคุมข้อมูลรายอื่น
				หรือตัวท่านเองด้วยเหตุบางประการได้
			</li>
			<li>
				สิทธิในการคัดค้านการประมวลผลข้อมูลส่วนบุคคล (Right to object):
				ท่านมีสิทธิในการคัดค้านการประมวลผลข้อมูลส่วนบุคคลของท่านได้
			</li>
		</ul>
		<p>
			ท่านสามารถติดต่อมายังเจ้าหน้าที่ของโครงการฯ ได้ เพื่อดำเนินการยื่นคำร้องดำเนินการตามสิทธิข้างต้น
			(รายละเอียดการติดต่อปรากฏในหัวข้อ “ช่องทางการติดต่อ” ด้านล่างนี้)
			ทั้งนี้ การใช้สิทธิดังกล่าวข้างต้นอาจมีการใช้ระยะเวลานานในการดำเนินการของทางโครงการฯ
			เพื่อดำเนินการให้สมประโยชน์ของท่านที่สุด
		</p>
	</section>

	<section class="flex flex-col gap-2">
		<h3>8. การส่งข้อมูลไปยังต่างประเทศ</h3>
		<p>
			ข้อมูลส่วนบุคคลของท่านอาจมีความจำเป็นที่จะถูกเก็บรวบรวมหรือประมวลผลในต่างประเทศผ่านการใช้บริการของบุคคลที่สาม
			เช่น Google (การเข้าสู่ระบบ) และ Cloudflare (ระบบเว็บไซต์และฐานข้อมูล)
			เพื่อประโยชน์ในการให้บริการและความสะดวกในการดำเนินกิจกรรมให้ลุล่วง
			ทั้งนี้โดยผ่านการคำนึงถึงความเหมาะสมและประโยชน์ของบุคคลเป็นสำคัญ
			ท่านสามารถติดต่อขอข้อมูลเพิ่มเติมเกี่ยวกับการส่งข้อมูลไปยังต่างประเทศได้จากเจ้าหน้าที่ของโครงการฯ
			(รายละเอียดการติดต่อปรากฏในหัวข้อ “ช่องทางการติดต่อ” ด้านล่างนี้)
		</p>
	</section>

